// Visual pass over every screen with the synthetic demo, in light and dark mode.
import { test, expect } from '@playwright/test'
import { mkdtempSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { launch } from './helpers'

for (const scheme of ['light', 'dark'] as const) {
  test(`screens (${scheme})`, async () => {
    const { app, page } = await launch(mkdtempSync(join(tmpdir(), 'bari-ud-')), scheme)
    const shot = (n: string) => page.screenshot({ path: join(import.meta.dirname, '..', 'test-results', 'screens', `${scheme}-${n}.png`) })
    await page.waitForTimeout(600)
    await shot('01-welcome')
    await page.getByText('Open synthetic demo').click()
    await page.getByText('Outstanding metadata tasks').waitFor()
    await shot('02-overview')
    await page.getByRole('button', { name: 'Explore data' }).first().click()
    await page.getByTestId('group-picker').click()
    await page.getByLabel('Search measures').fill('Sex')
    await page.keyboard.press('Enter')
    await page.waitForTimeout(500)
    await shot('03-explore-distribution')
    await page.getByTestId('analyze').click()
    await page.getByLabel('Show mean ± 95% CI on chart').check()
    await page.getByTestId('compute-stats').click()
    await expect(page.getByTestId('stats-panel')).toBeVisible()
    await page.getByTestId('stats-panel').scrollIntoViewIfNeeded()
    await page.waitForTimeout(400)
    await shot('04-distribution-stats')
    await page.getByRole('button', { name: 'Two measures' }).click()
    await page.waitForTimeout(600)
    await page.locator('.content').evaluate((el) => el.scrollTo(0, 0))
    await shot('05-scatter-fit')
    await page.getByTestId('stats-panel').scrollIntoViewIfNeeded()
    await shot('06-scatter-stats')
    await page.locator('.content').evaluate((el) => el.scrollTo(0, 0))
    await page.getByTestId('style-editor').click()
    await page.getByText('Publication', { exact: true }).click()
    await page.waitForTimeout(300)
    await shot('07-style-editor')
    await page.keyboard.press('Escape')
    await page.getByTestId('save-view').click()
    await shot('08-save-view-suggested')
    await page.keyboard.press('Enter')
    await page.getByRole('button', { name: 'Distribution' }).click()
    await page.getByTestId('save-view').click()
    await page.keyboard.press('Enter')
    await page.getByRole('button', { name: 'Saved views' }).click()
    await page.getByTestId('compare-tab').click()
    await page.getByTestId('new-board').click()
    await page.getByTestId('board-add-view').click()
    await page.getByRole('button', { name: 'Add all views' }).click()
    await page.getByRole('button', { name: 'Note', exact: true }).click()
    await page.locator('.board-note').fill('Synthetic demo: compare IL6 by sex with the IL6–PHQ-9 association.')
    await page.waitForTimeout(900)
    await shot('09-compare-board')
    await page.getByRole('button', { name: 'Measurements' }).click()
    await page.waitForTimeout(400)
    await shot('10-measurements')
    await page.getByRole('button', { name: 'Data quality' }).click()
    await shot('11-quality')
    await page.getByRole('button', { name: 'Export' }).click()
    await page.waitForTimeout(700)
    await shot('12-export')
    await app.close()
  })
}
